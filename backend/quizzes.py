def question_for_day(semester: str, day_ordinal: int) -> dict:
    """سؤال اليوم — يتبدل يومياً بالتناوب على بنك الفصل."""
    bank = QUESTION_BANKS.get(semester, QUESTION_BANKS["sem1"])
    return bank[day_ordinal % len(bank)]


def public_question(q: dict) -> dict:
    """نسخة السؤال المرسلة للواجهة — بدون كشف الإجابة الصحيحة."""
    return {
        "id": q["id"],
        "subject": q["subject"],
        "question": q["question"],
        "options": q["options"],
    }


def tip_for_day(day_ordinal: int) -> str:
    return TIPS[day_ordinal % len(TIPS)]
